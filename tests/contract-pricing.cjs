const fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const root=path.resolve(__dirname,'..');
const dom=new JSDOM(fs.readFileSync(path.join(root,'index.html'),'utf8'),{runScripts:'outside-only'});
const w=dom.window;
w.kpFlatCatalog=()=>[{id:'standard',name:'Стандарт',unit:'м²',rate:1600},{name:'Фиксированный пакет',unit:'шт',rate:5000}];
w.showToast=()=>{};w.eval(fs.readFileSync(path.join(root,'contract-pricing.js'),'utf8'));
const field=id=>w.document.getElementById('ct-'+id);
const input=(id,value,type='input')=>{field(id).value=value;field(id).dispatchEvent(new w.Event(type));};
input('tariff','catalog:0','change');input('area','100');
assert.equal(field('price').value,'160000');assert.equal(field('price').readOnly,true);
input('discount-mode','discount','change');input('discount-pct','10');
assert.equal(field('price').value,'144000');
const saved=w.contractPricingSnapshot();
w.kpFlatCatalog=()=>[{id:'standard',name:'Изменённый тариф',unit:'м²',rate:9999}];
w.resetContractPricing();w.applyContractPricing(saved);
assert.equal(field('rate').value,'1600');assert.equal(field('price').value,'144000');
assert.match(w.contractPricingLines(saved).join('\n'),/Стандарт/);
input('discount-mode','none','change');assert.equal(field('price').value,'160000');
input('area','80.25');input('rate','1234.56');input('discount-mode','discount','change');input('discount-pct','12.5');
assert.equal(field('price').value,'86689.26');
input('discount-pct','101');assert.equal(w.validateContractPricing(),false);assert.equal(field('price').value,'');
input('discount-pct','10');input('area','0');assert.equal(w.validateContractPricing(),false);
input('area','10.001');assert.equal(w.validateContractPricing(),false);
input('area','100');input('discount-pct','100');assert.equal(field('price').value,'0');assert.equal(w.validateContractPricing(),true);
input('discount-pct','');assert.equal(w.validateContractPricing(),false);
field('price').value='87654';w.applyContractPricing();assert.equal(field('price').value,'87654');assert.equal(field('price').readOnly,false);
w.resetContractPricing(75);assert.equal(field('area').value,'75');assert.equal(field('discount-mode').value,'none');
assert.equal(w.contractPricingLines(undefined).length,0);
console.log('Contract catalogue prices, discount toggles, decimal rounding, validation and frozen snapshots passed');
